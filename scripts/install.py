#!/usr/bin/env python3
"""Cross-platform Python installer for The Agency agents.

Reads AGENTS.json and installs agent files into AI coding tools.
No bash dependency — works on Windows, macOS, and Linux.

Usage:
    python scripts/install.py --tool claude-code           # all agents
    python scripts/install.py --tool claude-code --division engineering
    python scripts/install.py --list-installed --tool claude-code
    python scripts/install.py --verify --tool claude-code
    python scripts/install.py --uninstall --tool claude-code
"""

import argparse
import json
import os
import re
import shutil
import sys
import tempfile
from pathlib import Path, PurePosixPath
from typing import Any, cast

from _shared import REPO

INDEX_PATH = REPO / "AGENTS.json"
TOOLS_PATH = REPO / "tools.json"

# Agent ids in AGENTS.json are lowercase kebab-case.  Four shipped agents
# start with an underscore (_solution-*), so the first character may be "_".
_AGENT_ID_RE = re.compile(r"^[a-z0-9_][a-z0-9_-]*$")
_SLUG_RE = re.compile(r"^[a-z0-9_][a-z0-9_-]*$")
_ROSTER_MARKER = b"Generated by scripts/convert.py"


def _plugin_present(cfg: dict[str, Any], scope: str) -> bool:
    """Return True when a plugin-kind tool's output exists for the scope."""
    scopes = ["user", "project"] if scope == "both" else [scope]
    for s in scopes:
        for tmpl in cfg.get("dest", {}).get(s) or []:
            base = Path.home() if s == "user" else Path.cwd()
            if "*" in tmpl:
                if any(base.glob(tmpl)):
                    return True
            elif (base / tmpl).exists():
                return True
    return False


def _is_owned_roster(path: Path) -> bool:
    """True when a roster file carries the convert.py ownership marker."""
    try:
        with open(path, "rb") as f:
            return _ROSTER_MARKER in f.read(2048)
    except OSError:
        return False


def load_json(path: Path) -> dict[str, Any]:
    with open(path, encoding="utf-8") as f:
        return cast(dict[str, Any], json.load(f))


def slugify(name: str) -> str:
    s = name.lower()
    s = re.sub(r"[^a-z0-9]", "-", s)
    s = re.sub(r"-{2,}", "-", s)
    return s.strip("-")


def get_tool_cfg(tool: str) -> dict[str, Any]:
    tools = load_json(TOOLS_PATH).get("tools", {})
    if tool not in tools:
        print(f"Unknown tool: {tool}. Available: {', '.join(sorted(tools))}", file=sys.stderr)
        sys.exit(1)
    return cast(dict[str, Any], tools[tool])


def resolve_dest(tool: str, scope: str) -> list[tuple[Path, str]]:
    """Return list of (base_dir, filename_template)."""
    cfg = get_tool_cfg(tool)
    home = Path.home()
    results = []
    TEMPLATES = [
        "/{slug}.md", "/{slug}.toml", "/{slug}.yaml",
        "/{slug}/SKILL.md", "/{slug}/SOUL.md", "/{slug}/agent.yaml",
    ]
    for tmpl in cfg.get("dest", {}).get(scope, []):
        matched = False
        for pattern in TEMPLATES:
            if tmpl.endswith(pattern):
                base = tmpl[:-len(pattern)]
                resolved = home / base if scope == "user" else Path.cwd() / base
                results.append((resolved, pattern.lstrip("/")))
                matched = True
                break
        if not matched:
            # Keep a mid-path {slug} in the filename template so install_agent
            # can substitute it; the base is everything before the last {slug}.
            if "{slug}" in tmpl:
                idx = tmpl.rfind("{slug}")
                base = tmpl[:idx].rstrip("/")
                fname = tmpl[idx:]
            else:
                base = tmpl.rsplit("/", 1)[0] if "/" in tmpl else ""
                fname = tmpl.rsplit("/", 1)[-1] if "/" in tmpl else tmpl
            resolved = home / base if scope == "user" else Path.cwd() / base
            results.append((resolved, fname))
    return results


def _dest_dirs(tool: str, cfg: dict[str, Any], scope: str) -> list[tuple[Path, str]]:
    scopes = ["user", "project"] if scope == "both" else [scope]
    results: list[tuple[Path, str]] = []
    for s in scopes:
        if cfg.get("scope", {}).get(s):
            results.extend(resolve_dest(tool, s))
    return results


def _agent_slug(agent: dict[str, Any], tool_cfg: dict[str, Any]) -> str:
    """Return the on-disk slug for an agent, including any tool prefix."""
    slug_from = tool_cfg.get("slugFrom", "source")
    base = agent.get("id", "") if slug_from == "source" else slugify(agent.get("name", ""))
    if not isinstance(base, str) or not _SLUG_RE.fullmatch(base):
        raise ValueError(f"invalid slug for agent {agent.get('id')!r}")
    return f"{tool_cfg.get('slugPrefix') or ''}{base}"


def _validate_agent_entry(agent: dict[str, Any]) -> Path:
    """Validate an index entry and return its source path under REPO."""
    aid = agent.get("id")
    rel = agent.get("path")
    if not isinstance(aid, str) or not _AGENT_ID_RE.fullmatch(aid):
        raise ValueError(f"unsafe agent id: {aid!r}")
    if not isinstance(rel, str) or not rel:
        raise ValueError(f"missing path for {aid}")
    pure = PurePosixPath(rel)
    if pure.is_absolute() or ".." in pure.parts or "\\" in rel or pure.suffix != ".md":
        raise ValueError(f"unsafe path for {aid}: {rel!r}")
    repo = REPO.resolve()
    source = (repo / rel).resolve()
    if not source.is_relative_to(repo) or not source.is_file():
        raise ValueError(f"path escapes repository or is missing: {rel!r}")
    return source


def _safe_dest(dest_dir: Path, name_tmpl: str, slug: str | None = None) -> Path:
    """Resolve a destination lexically and reject escapes outside dest_dir.

    The final component is deliberately not resolved: an existing symlink is
    replaced on install and removed (not followed) on uninstall.
    """
    if slug is not None and not _SLUG_RE.fullmatch(slug):
        raise ValueError(f"unsafe slug: {slug!r}")
    rel = name_tmpl if slug is None else name_tmpl.replace("{slug}", slug)
    if "\\" in rel:
        raise ValueError(f"destination escapes target directory: {rel!r}")
    pure = PurePosixPath(rel)
    if pure.is_absolute() or ".." in pure.parts:
        raise ValueError(f"destination escapes target directory: {rel!r}")
    base = dest_dir.resolve()
    dest = base.joinpath(*pure.parts)
    if not dest.parent.resolve().is_relative_to(base):
        raise ValueError(f"destination escapes target directory: {rel!r}")
    return dest


def _atomic_copy(source: Path, dest: Path) -> None:
    """Copy through a temp file so existing symlinks are replaced, not followed."""
    dest.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(prefix=".agency-", suffix=".tmp", dir=str(dest.parent))
    os.close(fd)
    tmp = Path(tmp_name)
    try:
        shutil.copy2(source, tmp)
        os.replace(tmp, dest)
    except Exception:
        tmp.unlink(missing_ok=True)
        raise


def _build_source_index(integ_dir: Path) -> dict[tuple[str, str], Path]:
    index: dict[tuple[str, str], Path] = {}
    if not integ_dir.is_dir():
        return index
    for path in integ_dir.rglob("*"):
        if path.is_file():
            index[(path.stem, path.name)] = path
            index[(path.parent.name, path.name)] = path
    return index


def _find_source(integ_dir: Path, slug: str, name_tmpl: str,
                 index: dict[tuple[str, str], Path]) -> Path | None:
    rel = name_tmpl.replace("{slug}", slug)
    exact = integ_dir / rel
    if exact.is_file():
        return exact
    target_name = PurePosixPath(rel).name
    return index.get((slug, target_name))


def _selected_agents(divisions: set[str] | None,
                     agent_id: str | None) -> list[dict[str, Any]] | None:
    agents = cast(list[dict[str, Any]], load_json(INDEX_PATH).get("agents", []))
    if divisions:
        categories = {a.get("category") for a in agents}
        unknown = sorted(set(divisions) - categories)
        if unknown:
            print(f"ERROR: unknown division(s): {', '.join(unknown)}", file=sys.stderr)
            return None
        agents = [a for a in agents if a.get("category") in divisions]
    if agent_id:
        matches = [a for a in agents if a.get("id") == agent_id]
        if not matches:
            print(f"ERROR: unknown agent id: {agent_id}", file=sys.stderr)
            return None
        agents = matches
    return agents


def _owned_paths(dest_dir: Path, name_tmpl: str, slug: str) -> list[Path]:
    paths: list[Path] = []
    templates = [name_tmpl]
    if name_tmpl.startswith("{slug}/") or "/{slug}/" in name_tmpl:
        templates.append("{slug}")
    for tmpl in templates:
        try:
            paths.append(_safe_dest(dest_dir, tmpl, slug))
        except ValueError:
            continue
    return paths


def install_agent(agent: dict[str, Any], tool_cfg: dict[str, Any],
                  dest_dirs: list[tuple[Path, str]],
                  source_index: dict[tuple[str, str], Path] | None = None) -> int:
    """Install one agent to all destinations. Returns 1 when installed."""
    source = _validate_agent_entry(agent)
    slug = _agent_slug(agent, tool_cfg)
    fmt = tool_cfg.get("format", "identity")
    integ = REPO / "integrations" / tool_cfg["kebab"]
    if fmt != "identity" and source_index is None:
        source_index = _build_source_index(integ)

    copied = 0
    for dest_dir, name_tmpl in dest_dirs:
        try:
            dest = _safe_dest(dest_dir, name_tmpl, slug)
        except ValueError as exc:
            print(f"  skip {agent.get('id')}: {exc}", file=sys.stderr)
            continue
        if fmt == "identity":
            src: Path | None = source
        else:
            src = _find_source(integ, slug, name_tmpl, source_index or {})
        if src is None:
            print(f"  skip {agent.get('id')}: converted source missing for {name_tmpl}",
                  file=sys.stderr)
            continue
        _atomic_copy(src, dest)
        copied += 1
    return 1 if copied else 0


def install_tool(tool: str, divisions: set[str] | None,
                 agent_id: str | None, scope: str = "user") -> int:
    cfg = get_tool_cfg(tool)
    kind = cfg.get("installKind", "per-agent")

    if kind == "plugin":
        print(f"{tool}: plugin type, use convert.py")
        return 0

    dest_dirs = _dest_dirs(tool, cfg, scope)
    if not dest_dirs:
        print(f"ERROR: {tool}: no destinations for scope={scope}; try --scope project",
              file=sys.stderr)
        return -1

    agents = _selected_agents(divisions, agent_id)
    if agents is None:
        return -1

    if kind == "roster":
        if divisions or agent_id:
            print(f"ERROR: {tool} is a roster tool; --division/--agent filters are not supported",
                  file=sys.stderr)
            return -1
        integ = REPO / "integrations" / cfg["kebab"]
        copied = 0
        for dest_dir, name_tmpl in dest_dirs:
            source = integ / name_tmpl
            if not source.is_file():
                print(f"ERROR: converted roster missing: {source}. Run convert first.",
                      file=sys.stderr)
                return -1
            try:
                dest = _safe_dest(dest_dir, name_tmpl)
            except ValueError as exc:
                print(f"ERROR: {exc}", file=sys.stderr)
                return -1
            _atomic_copy(source, dest)
            copied += 1
        print(f"{tool}: roster installed to {copied} destination(s)")
        return 1 if copied else -1

    source_index = None
    if cfg.get("format", "identity") != "identity":
        integ = REPO / "integrations" / cfg["kebab"]
        if not integ.is_dir():
            print(f"ERROR: {integ} missing. Run: python scripts/convert.py --tool {tool}",
                  file=sys.stderr)
            return -1
        source_index = _build_source_index(integ)

    installed = 0
    for agent in agents:
        try:
            installed += install_agent(agent, cfg, dest_dirs, source_index)
        except ValueError as exc:
            print(f"ERROR: unsafe agent entry: {exc}", file=sys.stderr)
            return -1

    print(f"{tool}: {installed} agents -> {dest_dirs[0][0]}")
    return installed


def list_installed(tool: str, scope: str = "user") -> int:
    cfg = get_tool_cfg(tool)
    dest_dirs = _dest_dirs(tool, cfg, scope)
    if not dest_dirs:
        print(f"{tool}: no destinations for scope={scope}", file=sys.stderr)
        return -1

    if cfg.get("installKind") == "plugin":
        present = _plugin_present(cfg, scope)
        print(f"{tool}: plugin {'installed' if present else 'not installed'}")
        return 1 if present else 0

    if cfg.get("installKind") == "roster":
        found = 0
        for dest_dir, name_tmpl in dest_dirs:
            if _safe_dest(dest_dir, name_tmpl).is_file():
                found += 1
        print(f"{tool}: roster {'installed' if found else 'not installed'}")
        return found

    agents = _selected_agents(None, None) or []
    count = 0
    for agent in agents:
        try:
            slug = _agent_slug(agent, cfg)
            if any(path.exists() for dest_dir, name_tmpl in dest_dirs
                   for path in _owned_paths(dest_dir, name_tmpl, slug)):
                count += 1
        except ValueError:
            continue
    print(f"{tool}: {count} agents installed")
    return count


def verify_install(tool: str, divisions: set[str] | None = None,
                   agent_id: str | None = None, scope: str = "user") -> bool:
    cfg = get_tool_cfg(tool)
    dest_dirs = _dest_dirs(tool, cfg, scope)
    if not dest_dirs:
        print(f"FAIL: {tool} has no destinations for scope={scope}")
        return False

    if cfg.get("installKind") == "plugin":
        present = _plugin_present(cfg, scope)
        print("OK: plugin present" if present else "FAIL: plugin missing")
        return present

    agents = _selected_agents(divisions, agent_id)
    if agents is None:
        return False

    if cfg.get("installKind") == "roster":
        ok = True
        for dest_dir, name_tmpl in dest_dirs:
            if not _safe_dest(dest_dir, name_tmpl).is_file():
                print(f"  Missing roster file: {name_tmpl}")
                ok = False
        print("OK: roster file verified" if ok else "FAIL: roster file missing")
        return ok

    missing: list[str] = []
    for agent in agents:
        try:
            slug = _agent_slug(agent, cfg)
        except ValueError as exc:
            print(f"  invalid agent entry: {exc}", file=sys.stderr)
            missing.append(str(agent.get("id")))
            continue
        for dest_dir, name_tmpl in dest_dirs:
            if not any(path.exists() for path in _owned_paths(dest_dir, name_tmpl, slug)):
                missing.append(str(agent.get("id")))
                break
    if missing:
        print(f"  Missing: {len(missing)} agents")
        return False
    print(f"OK: {len(agents)} agents verified for {tool}")
    return True


def uninstall_tool(tool: str, agent_id: str | None,
                   divisions: set[str] | None = None,
                   scope: str = "user") -> int:
    cfg = get_tool_cfg(tool)
    kind = cfg.get("installKind", "per-agent")
    if kind == "plugin":
        print(f"{tool}: plugin type; remove the plugin directory manually")
        return 0

    dest_dirs = _dest_dirs(tool, cfg, scope)
    if not dest_dirs:
        print(f"ERROR: {tool}: no destinations for scope={scope}; try --scope project",
              file=sys.stderr)
        return -1

    agents = _selected_agents(divisions, agent_id)
    if agents is None:
        return -1

    if kind == "roster":
        if divisions or agent_id:
            print(f"ERROR: {tool} is a roster tool; --division/--agent filters are not supported",
                  file=sys.stderr)
            return -1
        removed = 0
        skipped = 0
        for dest_dir, name_tmpl in dest_dirs:
            dest = _safe_dest(dest_dir, name_tmpl)
            if dest.is_file() and _is_owned_roster(dest):
                dest.unlink()
                removed += 1
            elif dest.is_file():
                skipped += 1
        if skipped:
            print(f"WARNING: {tool}: refusing to remove {skipped} roster file(s) "
                  "not generated by The Agency", file=sys.stderr)
        print(f"{tool}: roster removed from {removed} destination(s)")
        return removed

    removed_agents = 0
    for agent in agents:
        try:
            slug = _agent_slug(agent, cfg)
        except ValueError as exc:
            print(f"ERROR: {exc}", file=sys.stderr)
            return -1
        hit = False
        for dest_dir, name_tmpl in dest_dirs:
            for path in sorted(set(_owned_paths(dest_dir, name_tmpl, slug)),
                               key=lambda p: len(p.parts), reverse=True):
                if path.is_symlink():
                    path.unlink()
                    hit = True
                elif path.is_dir():
                    shutil.rmtree(path)  # audit-security: allow (install destination)
                    hit = True
                elif path.is_file():
                    path.unlink()
                    hit = True
        if hit:
            removed_agents += 1
    print(f"{tool}: {removed_agents} agents removed")
    return removed_agents


def main() -> None:
    parser = argparse.ArgumentParser(description="Install The Agency agents")
    parser.add_argument("--tool", default="claude-code", help="Target tool")
    parser.add_argument("--division", help="Comma-separated division filter")
    parser.add_argument("--agent", help="Single agent ID")
    parser.add_argument("--scope", default="user", choices=["user", "project", "both"],
                        help="Install scope: user, project, or both (default: user)")
    parser.add_argument("--uninstall", action="store_true")
    parser.add_argument("--list-installed", action="store_true")
    parser.add_argument("--verify", action="store_true")
    args = parser.parse_args()

    divisions = {d.strip() for d in args.division.split(",") if d.strip()} if args.division else None

    if args.list_installed:
        n = list_installed(args.tool, scope=args.scope)
        sys.exit(0 if n >= 0 else 1)
    if args.verify:
        ok = verify_install(args.tool, divisions, args.agent, scope=args.scope)
        sys.exit(0 if ok else 1)
    if args.uninstall:
        n = uninstall_tool(args.tool, args.agent, divisions, scope=args.scope)
        sys.exit(0 if n >= 0 else 1)

    n = install_tool(args.tool, divisions, args.agent, scope=args.scope)
    if n <= 0:
        kind = get_tool_cfg(args.tool).get("installKind", "per-agent")
        sys.exit(0 if kind == "plugin" and n == 0 else 1)
    print(f"Done. {n} agents installed.")


if __name__ == "__main__":
    main()
